"""Automatic labels from the sample tree, and the deterministic metrics they allow (Faz 7).

    python eval/auto_labels.py                       # write eval/labels/auto/samples.yaml and print metrics
    python eval/auto_labels.py --json out/eval/auto_metrics.json

EVTX-ATTACK-SAMPLES files sit in one folder per ATT&CK tactic. That folder is the
only label derived here: no key events, no expected
assessment. It supports three questions over every sample in eval/samples.lock,
without the model:
- does Hayabusa detect anything, and does the tool send a group to the model?
- do the detections carry the folder's tactic?
- how much of the output does the event dictionary describe?

The folder is the sample author's classification, not ground truth: a sample under
Lateral Movement can legitimately also show Execution. "Tactic agreement" counts
samples where the folder's tactic appears at all, which is a weak check.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from dataclasses import asdict, dataclass
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import yaml  # noqa: E402

from evtx_triage.config import load_config  # noqa: E402
from evtx_triage.ingest.hayabusa_csv import InputContractError  # noqa: E402
from evtx_triage.pipeline import run_deterministic  # noqa: E402

# ATT&CK v19 split Defense Evasion into Stealth (TA0005, renamed) and Defense Impairment (TA0112).
FOLDER_TACTICS: dict[str, list[str]] = {
    "Command and Control": ["Command and Control"],
    "Credential Access": ["Credential Access"],
    "Defense Evasion": ["Stealth", "Defense Impairment"],
    "Discovery": ["Discovery"],
    "Execution": ["Execution"],
    "Lateral Movement": ["Lateral Movement"],
    "Persistence": ["Persistence"],
    "Privilege Escalation": ["Privilege Escalation"],
}


@dataclass
class SampleMetrics:
    evtx: str
    folder: str
    status: str
    detections: int = 0
    groups: int = 0
    selected_groups: int = 0
    tactic_seen: bool | None = None  # None: the folder names no tactic
    tactic_in_selected: bool | None = None
    rows_known: int = 0
    ingest_errors: int = 0


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--lock", type=Path, default=Path("eval/samples.lock"))
    parser.add_argument("--csv-dir", type=Path, default=Path("data/hayabusa_csv/per_evtx"))
    parser.add_argument("--config", type=Path, default=Path("config/default.toml"))
    parser.add_argument("--labels-out", type=Path, default=Path("eval/labels/auto/samples.yaml"))
    parser.add_argument("--json", type=Path)
    args = parser.parse_args()

    lock = json.loads(args.lock.read_text(encoding="utf-8"))
    config = load_config(args.config)

    labels = []
    results: list[SampleMetrics] = []
    for entry in lock["samples"]:
        folder = entry["evtx"].split("/")[0] if "/" in entry["evtx"] else "."
        expected = FOLDER_TACTICS.get(folder, [])
        labels.append(
            {"evtx": entry["evtx"], "csv": entry["csv"], "folder": folder, "expected_tactics": expected}
        )
        metrics = SampleMetrics(evtx=entry["evtx"], folder=folder, status=str(entry["status"]))
        results.append(metrics)
        if entry["status"] != "ok":
            continue
        try:
            result = run_deterministic(config, args.csv_dir / entry["csv"])
        except (InputContractError, OSError) as exc:
            metrics.status = f"unreadable: {exc}"
            continue
        metrics.detections = len(result.events)
        metrics.groups = len(result.groups)
        metrics.selected_groups = len(result.selected)
        metrics.rows_known = sum(1 for event in result.events if event.description is not None)
        metrics.ingest_errors = len(result.ingest.errors)
        if expected:
            metrics.tactic_seen = any(set(event.tactics_resolved) & set(expected) for event in result.events)
            metrics.tactic_in_selected = any(
                set(event.tactics_resolved) & set(expected)
                for group in result.selected
                for event in group.events
            )

    args.labels_out.parent.mkdir(parents=True, exist_ok=True)
    header = (
        "# Generated by eval/auto_labels.py from eval/samples.lock. Do not edit by hand.\n"
        "# The only label is the sample's tactic folder in EVTX-ATTACK-SAMPLES; it is the\n"
        "# sample author's classification, not ground truth.\n"
    )
    args.labels_out.write_text(
        header + yaml.safe_dump({"samples": labels}, sort_keys=False, allow_unicode=True),
        encoding="utf-8",
        newline="\n",
    )

    columns = ("files", "blocked", "none", "detect", "to model", "tactic", "in sel")
    print(f"{'folder':<24} " + " ".join(f"{name:>8}" for name in columns))
    folders = sorted({item.folder for item in results})
    for folder in [*folders, "TOTAL"]:
        chosen = results if folder == "TOTAL" else [item for item in results if item.folder == folder]
        detected = [item for item in chosen if item.detections]
        judged = [item for item in detected if item.tactic_seen is not None]
        cells = [
            str(len(chosen)),
            str(sum(item.status.startswith("blocked") for item in chosen)),
            str(sum(item.status == "no detections" for item in chosen)),
            str(len(detected)),
            str(sum(1 for item in detected if item.selected_groups)),
            f"{sum(bool(item.tactic_seen) for item in judged)}/{len(judged)}",
            f"{sum(bool(item.tactic_in_selected) for item in judged)}/{len(judged)}",
        ]
        print(f"{folder:<24} " + " ".join(f"{cell:>8}" for cell in cells))
    rows = sum(item.detections for item in results)
    known = sum(item.rows_known for item in results)
    print(f"\ndetections {rows}, described by the dictionary {known} ({known / max(rows, 1):.1%})")
    print(f"ingest errors {sum(item.ingest_errors for item in results)}")
    print(f"selected groups (sent to the model) {sum(item.selected_groups for item in results)}")
    statuses = Counter(item.status.split(":")[0] for item in results)
    print(f"statuses {dict(statuses)}")
    print(f"labels written: {args.labels_out}")

    if args.json:
        args.json.parent.mkdir(parents=True, exist_ok=True)
        args.json.write_text(
            json.dumps([asdict(item) for item in results], indent=2) + "\n", encoding="utf-8"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
